"""Every numbered paragraph of every stored guidance document carries a decision.

The Act's coverage ledger makes "nobody looked" impossible to confuse with "nothing there". This is
the same guarantee for Commission guidance, one level down: each document's `coverage.yaml` gives
every paragraph in its `paragraphs.yaml` a decision, or lists it as awaiting review — declared debt,
never silence.

- `used`: quoted in a snippet that a question or rule is handed.
- `not_followed`: quoted in a snippet that nothing is handed, with the reason on record.
- `no_effect`: changes no answer this product gives, with the reason.

What the check can prove is structural: the paragraph list comes from the pinned PDF, not from a
person; no paragraph is skipped; every quote matches the extracted text; a decision never rests on
a paragraph the two extraction engines read differently until a person has checked the page. Whether
a decision is RIGHT is a reading of the text, and stays a reviewer's call.
"""

from __future__ import annotations

import re
from enum import StrEnum
from pathlib import Path

import yaml
from pydantic import BaseModel, ConfigDict, Field, model_validator

from aiact.guidance import load_snippet
from aiact.guidance_text import comparable, extract_paragraphs, pdfium_body_text

PARAGRAPHS_FILE = "paragraphs.yaml"
COVERAGE_FILE = "coverage.yaml"
_HEADER = (
    "# GENERATED by scripts/extract_guidance_paragraphs.py from source.pdf. Do not edit: the\n"
    "# PDF is authoritative and this is a machine extraction of its numbered paragraphs.\n"
    "# `engines_agree` says whether PDFium read the same characters as pdfplumber, spacing aside.\n"
)
_ELISION = "[…]"


class ParagraphDecision(StrEnum):
    USED = "used"
    NOT_FOLLOWED = "not_followed"
    NO_EFFECT = "no_effect"


class Decision(BaseModel):
    model_config = ConfigDict(extra="forbid")

    decision: ParagraphDecision
    reason: str = ""

    @model_validator(mode="after")
    def _explained(self) -> Decision:
        if self.decision is not ParagraphDecision.USED and not self.reason.strip():
            raise ValueError(f"decision {self.decision.value} requires a reason")
        return self


class VisualCheck(BaseModel):
    model_config = ConfigDict(extra="forbid")

    checked_by: str = Field(min_length=1)
    note: str = ""


class GuidanceCoverage(BaseModel):
    model_config = ConfigDict(extra="forbid")

    awaiting_review: str = ""
    decisions: dict[int, Decision] = {}
    visually_checked: dict[int, VisualCheck] = {}


def parse_ranges(text: str) -> set[int]:
    """`"1-5, 7, 9-10"` -> {1, 2, 3, 4, 5, 7, 9, 10}."""
    numbers: set[int] = set()
    for part in filter(None, (piece.strip() for piece in text.split(","))):
        low, _, high = part.partition("-")
        numbers.update(range(int(low), int(high or low) + 1))
    return numbers


def _front(field: str, raw: str) -> str:
    match = re.search(rf"^{field}:\s*(.+?)\s*$", raw, re.M)
    return match.group(1).strip() if match else ""


def body_layout(document_dir: Path) -> tuple[frozenset[float], float]:
    source = (document_dir / "source.md").read_text(encoding="utf-8")
    sizes = yaml.safe_load(_front("body_font_sizes", source) or "null")
    limit = yaml.safe_load(_front("body_bottom_limit", source) or "null")
    if not sizes or limit is None:
        raise ValueError(
            f"{document_dir.name}/source.md declares no body_font_sizes/body_bottom_limit"
        )
    return frozenset(float(size) for size in sizes), float(limit)


def render_paragraphs(document_dir: Path) -> str:
    """The `paragraphs.yaml` text for a document, extracted afresh from its PDF."""
    pdf = document_dir / "source.pdf"
    sizes, limit = body_layout(document_dir)
    paragraphs = extract_paragraphs(pdf, sizes, limit)
    other_engine = pdfium_body_text(pdf, sizes, limit)
    source = (document_dir / "source.md").read_text(encoding="utf-8")
    data = {
        "document": _front("reference", source),
        "pdf_sha256": _front("pdf_sha256", source),
        "paragraphs": [
            {
                "number": paragraph.number,
                "pages": list(paragraph.pages),
                "engines_agree": comparable(paragraph.text) in other_engine,
                "text": paragraph.text,
            }
            for paragraph in paragraphs
        ],
    }
    return _HEADER + yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=100)


def _snippet_paragraphs(path: Path) -> list[int]:
    value = _front("paragraphs", path.read_text(encoding="utf-8"))
    return [int(number) for number in yaml.safe_load(value or "[]")]


def guidance_coverage_errors(root: Path, consumed_refs: set[str]) -> list[str]:
    """Every coverage defect across the guidance store, in deterministic order.

    `consumed_refs` are the snippets a question or rule is handed — the interpretation links, which
    `norm_traceability` already proves match the runtime uses one for one.
    """
    errors: list[str] = []
    for document_dir in sorted(path for path in root.iterdir() if path.is_dir()):
        doc = document_dir.name
        stored = yaml.safe_load((document_dir / PARAGRAPHS_FILE).read_text(encoding="utf-8"))
        source = (document_dir / "source.md").read_text(encoding="utf-8")
        if stored["pdf_sha256"] != _front("pdf_sha256", source):
            errors.append(f"{doc}/{PARAGRAPHS_FILE} was extracted from a different PDF")
        paragraphs = {item["number"]: item for item in stored["paragraphs"]}
        numbers = set(paragraphs)
        if numbers != set(range(1, len(numbers) + 1)):
            errors.append(f"{doc} paragraph numbering is not 1 to {len(numbers)} without gaps")

        coverage = GuidanceCoverage.model_validate(
            yaml.safe_load((document_dir / COVERAGE_FILE).read_text(encoding="utf-8")) or {}
        )
        awaiting = parse_ranges(coverage.awaiting_review)
        decided = set(coverage.decisions)
        for number in sorted(decided & awaiting):
            errors.append(f"{doc} ¶{number} is both decided and awaiting review")
        for number in sorted(numbers - decided - awaiting):
            errors.append(f"{doc} ¶{number} has no decision and is not listed as awaiting review")
        for number in sorted((decided | awaiting | set(coverage.visually_checked)) - numbers):
            errors.append(f"{doc} ¶{number} is not a paragraph of the document")
        for number in sorted(decided & numbers):
            if not paragraphs[number]["engines_agree"] and number not in coverage.visually_checked:
                errors.append(
                    f"{doc} ¶{number} is decided, but the two engines read it differently and no "
                    "one has checked it against the page"
                )
        for number in sorted(set(coverage.visually_checked) & numbers):
            if paragraphs[number]["engines_agree"]:
                errors.append(f"{doc} ¶{number} is marked visually checked, but the engines agree")

        quoted: dict[int, list[str]] = {}
        for path in sorted((document_dir / "snippets").glob("*.md")):
            ref = f"{doc}/{path.stem}"
            cited = _snippet_paragraphs(path)
            if not cited:
                errors.append(f"{ref} names no `paragraphs:` it quotes")
                continue
            unknown = [number for number in cited if number not in paragraphs]
            if unknown:
                errors.append(f"{ref} quotes paragraph(s) {unknown} the document does not have")
                continue
            for number in cited:
                quoted.setdefault(number, []).append(ref)
            extracted = comparable(" ".join(paragraphs[number]["text"] for number in cited))
            for piece in load_snippet(ref, root).body.split(_ELISION):
                if comparable(piece) not in extracted:
                    errors.append(
                        f"{ref} quote does not match the extracted text of ¶{cited}: "
                        f"{piece.strip()[:60]!r}"
                    )
            expected = (
                ParagraphDecision.USED if ref in consumed_refs else ParagraphDecision.NOT_FOLLOWED
            )
            for number in cited:
                decision = coverage.decisions.get(number)
                if decision is None or decision.decision is not expected:
                    errors.append(
                        f"{doc} ¶{number} is quoted by {ref}, which "
                        f"{'is' if expected is ParagraphDecision.USED else 'is not'} handed to a "
                        f"question or rule, so its decision must be {expected.value}"
                    )
        for number, decision in sorted(coverage.decisions.items()):
            if decision.decision is not ParagraphDecision.NO_EFFECT and number not in quoted:
                errors.append(
                    f"{doc} ¶{number} is {decision.decision.value} but no snippet quotes it"
                )
    return errors
