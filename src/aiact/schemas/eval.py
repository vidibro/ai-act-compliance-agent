"""EVAL ONLY — ground-truth cases for measuring the agent. Not part of the Regulation.

Two layers, because the agent does two different jobs:

  LAYER 1 — CLASSIFICATION (ClassificationCase). Given a use-case description, what RISK CLASS is
            it? prohibited / high_risk / not_high_risk / minimal. This is where the project's
            headline lives: the FLIP — a one-sentence edit that moves a use case from not_high_risk
            to high_risk via the Art. 6(3) profiling carve-back. Hand-authored: the description is
            the input, the class is known.

  LAYER 2 — OBLIGATION CHECKING (GoldenCase / GoldenSet). Given a high-risk system's documentation,
            does it satisfy each obligation? pass / gap / inadequate. Generated by degrading a
            known-compliant reference document in one known way, so ground truth is exact.

Layer 1 feeds the classification graph (M3); Layer 2 feeds the gap-analysis checker (M4). A case's
ground truth is never itself a judgement — it is fixed by construction (Layer 2) or by the author
stating the decisive fact and the class it forces (Layer 1).
"""

from __future__ import annotations

from enum import StrEnum
from typing import Literal

from pydantic import BaseModel, ConfigDict, field_validator, model_validator

from aiact.schemas.enums import (
    AnnexIIIArea,
    AnnexIProduct,
    DerogationCondition,
    ProhibitedPractice,
    RiskClass,
    ScopeExclusion,
    TransparencyDuty,
    Verdict,
)

# dev  = cases you may tune against (prompts, thresholds).
# test = HELD OUT. Never tuned against; the only split whose score you are allowed to report.
# Default is "test": a new case is protected from tuning until deliberately opted into dev, so you
# cannot silently overfit to it.
Split = Literal["dev", "test"]


class AblationType(StrEnum):
    """EVAL ONLY — not part of the Regulation. Describes how a requirement was degraded when
    generating a synthetic test document from the complete reference document. Because we know
    exactly what was altered, ground truth is exact."""

    REMOVED = "removed"
    """Section deleted outright. Expected verdict: GAP.
    NOTE: measured, not assumed. A realistic reference document cross-references itself, so
    deleting a section does not delete its topic words elsewhere — the keyword baseline scores
    1/7 here. Deletion is not the freebie it looks like."""

    PRESENT_BUT_INADEQUATE = "present_but_inadequate"
    """Section reduced to an empty assertion. Expected verdict: INADEQUATE.
    Defeats keyword matching — the most diagnostic class of example."""

    DISTRACTOR = "distractor"
    """Replaced with plausible-sounding but non-responsive content (e.g. a 'responsible AI'
    marketing section standing in for Art. 10 data governance). Expected verdict: GAP.
    Tests whether the agent distinguishes marketing from evidence of compliance.
    A false PASS here is the most dangerous failure mode of a compliance tool."""

    UNTOUCHED = "untouched"
    """Left intact. Expected verdict: PASS. Measures FALSE POSITIVES — a checker that flags
    everything is useless. Untouched requirements matter as much as ablated ones."""


class Difficulty(StrEnum):
    """EVAL ONLY. How hard the decisive fact is to locate in the input. Enables reporting
    accuracy per difficulty band instead of one meaningless aggregate number."""

    OBVIOUS = "obvious"
    """The decisive fact is stated plainly (e.g. 'returns a candidate fit score')."""

    BURIED = "buried"
    """The decisive fact is present but buried among features and vague marketing language.
    A drop in accuracy here means the agent is keyword-matching, not reading."""

    AMBIGUOUS = "ambiguous"
    """Genuinely contestable — reasonable experts could disagree. Reported separately;
    NEEDS_REVIEW is an acceptable answer here."""

    INSUFFICIENT = "insufficient"
    """The decisive fact is ABSENT. The law is clear and the experts would agree — the DESCRIPTION
    simply never says. Deliberately not folded into `ambiguous`: that band is about contested law,
    this one is about missing input, and averaging them would make both unreadable.

    NEEDS_REVIEW is the only correct answer here, and it is the band where a confident verdict is
    worst: silence is not evidence of absence, so reading 'the text never mentions ranking' as 'the
    system does not rank' hands a provider a derogation they never claimed and cannot support
    (Art. 6(3) puts the burden on establishing the condition; Art. 6(4) requires it documented)."""


class GoldenCase(BaseModel):
    """One synthetic document plus the verdict every applicable rule should receive."""

    case_id: str  # "AIA-HR-A14__present_but_inadequate"
    system_id: str  # which reference system this was generated from
    document_path: str  # repo-relative path to the generated case document
    raw_text: str  # the document itself, as the checker will see it
    ablated_rule_id: str | None  # None for the pristine (untouched) case
    ablation: AblationType
    difficulty: Difficulty
    split: Split = "test"  # dev = tunable; test = held out, the only reportable score
    expected: dict[str, Verdict]  # rule_id -> expected verdict, for ALL applicable rules

    @model_validator(mode="after")
    def _ablated_rule_is_expected(self) -> GoldenCase:
        """The degraded rule must appear in `expected` — otherwise the case measures nothing."""
        if self.ablated_rule_id is not None and self.ablated_rule_id not in self.expected:
            raise ValueError(
                f"{self.case_id}: ablated rule {self.ablated_rule_id!r} carries no "
                f"expected verdict."
            )
        if self.ablation == AblationType.UNTOUCHED and self.ablated_rule_id is not None:
            raise ValueError(
                f"{self.case_id}: an untouched case degrades nothing, so ablated_rule_id "
                f"must be None."
            )
        return self


class GoldenSet(BaseModel):
    """All cases generated from one reference document, for one act version."""

    system_id: str
    reference_path: str
    act_version_date: str
    spec_version: str
    cases: list[GoldenCase]

    def for_split(self, split: Split | Literal["all"]) -> list[GoldenCase]:
        """Cases in one split. Tune against `dev`; report only `test`."""
        if split == "all":
            return list(self.cases)
        return [c for c in self.cases if c.split == split]


# ==================================================================================================
# LAYER 1 — classification
# ==================================================================================================
class ClassificationCase(BaseModel):
    """One use-case description with its known risk class and the decisive sub-answers.

    The `description` is the ONLY input a classifier sees. Everything else is the answer key. The
    validators below re-enforce the same legal invariants the real classifier must obey
    (classification.py), so the ground truth cannot quietly contradict the law it measures."""

    # An unknown key is a REJECTED case, not an ignored one. The default would silently drop a
    # misspelled or renamed pin, and a pin that is dropped is a node that goes unmeasured while the
    # YAML still reads as though it were checked — the exact failure the per-node scoring exists to
    # surface.
    model_config = ConfigDict(extra="forbid")

    case_id: str  # "cv_parsing_plus_scoring"
    description: str  # the use-case description the classifier reads — the input
    expected_risk_class: RiskClass

    expected_is_ai_system: bool
    """Art. 3(1) — is the described system an AI system at all? REQUIRED, and the only sub-answer
    that is.

    Every other field is optional because a case pins only what decides it. This one is asked on
    every case, first, and a `false` routes straight to `minimal` and skips the entire cascade —
    Art. 2, Art. 5 and both Art. 6 doors are never reached. One wrong answer here clears any system
    there is, which is why it may not be left to a default: omitting it must fail loudly rather
    than quietly assert `true` on a case nobody checked.

    Art. 3(1) turns on INFERENCE — a machine-based system that infers, from its input, how to
    generate outputs. Software that applies rules a person wrote is outside it however
    sophisticated, so a set where every case answers `true` measures nothing about this node."""

    # The "why" — the decisive sub-answers a correct classifier should also produce. Optional so a
    # case only pins what actually decides it.
    expected_scope_exclusion: ScopeExclusion | None = None
    """Art. 2 — WHICH paragraph puts this system outside the Regulation. Set exactly when the class
    is OUT_OF_SCOPE (see the validator)."""

    scope_exclusion_basis: str = ""
    """WHY that paragraph applies. Mandatory whenever an exclusion is set, same pairing as
    `expected_transparency_obligation` / `transparency_basis`: an exclusion that cannot show its
    working is how a wrong label survives. The exclusions are narrow enough — "exclusively"
    military, "sole purpose" of research, "purely" personal — that the argument is the answer."""

    expected_prohibited_practice: ProhibitedPractice | None = None
    """Art. 5(1) — WHICH point bans the practice. Set exactly when the class is PROHIBITED.

    WHETHER a case is prohibited is fixed by its class, so only the point carries information — and
    it is the half a bare boolean lost. Two cases can both be prohibited for entirely different
    reasons, and a key that cannot tell them apart cannot catch a run that reached the right class
    by the wrong prohibition."""

    @property
    def expected_prohibited(self) -> bool:
        """Art. 5 — whether the practice is banned at all, derived rather than stored so it cannot
        disagree with the point above."""
        return self.expected_prohibited_practice is not None
    expected_annex_i_product: AnnexIProduct | None = None
    """Art. 6(1)(a) — the product family whose safety component this system is, or None."""

    expected_third_party_assessment: bool | None = None
    """Art. 6(1)(b) — whether that product needs a notified body. Art. 6(1) is a CONJUNCTION, so a
    case that sets the product without this pins only half the test."""

    expected_annex_iii_area: AnnexIIIArea | None = None  # Art. 6(2), Annex III
    expected_performs_profiling: bool | None = None  # Art. 6(3) carve-back
    expected_derogation: DerogationCondition | None = None  # Art. 6(3)(a)-(d)

    expected_poses_significant_risk: bool | None = None
    """Art. 6(3), first subparagraph — does the system pose a significant risk of harm, including
    by materially influencing the outcome of decision making?

    The other half of a conjunction whose first half is `expected_derogation`, and a case naming a
    condition without this pins only half the test — the same gap `expected_third_party_assessment`
    fills for Art. 6(1). A `true` here is the interesting label: it is a use case that satisfies a
    condition under (a)-(d) and is high-risk anyway, which is the shape of case a set can most
    easily end up with none of."""
    expected_transparency_duties: list[TransparencyDuty] = []
    """Art. 50 — EVERY duty that attaches, whoever owes it. Applies regardless of the risk tier.

    A list because the duties are cumulative: a system that drafts published copy and talks to
    people owes 50(1) and 50(2), and a key holding one flag cannot say a run found only half of
    them. BOTH ROLES COUNT — (1) and (2) bind the provider, (3) and (4) the deployer. A key that
    recorded only the provider's would mark a correct deployer-side finding wrong, and a report
    silent about a duty its deployers certainly owe is less useful, not more rigorous.

    Empty is the ordinary answer and is a real one: no Art. 50 duty attaches."""

    @field_validator("expected_transparency_duties")
    @classmethod
    def _canonical_duty_order(cls, v: list[TransparencyDuty]) -> list[TransparencyDuty]:
        """Paragraph order, de-duplicated — the same order `_parse_duties` produces. The key and
        the run are compared as lists, so an author writing them in another order would score a
        correct answer wrong."""
        return sorted(dict.fromkeys(v), key=lambda d: (d.paragraph, d.value))

    @property
    def expected_transparency_obligation(self) -> bool:
        """Art. 50 — whether ANY duty attaches, derived rather than stored so it cannot disagree
        with the list above."""
        return bool(self.expected_transparency_duties)

    transparency_basis: str = ""
    """WHY those paragraphs attach — or why none does. Compelled by the validator whenever a duty
    is claimed, and by the golden-set tests in BOTH directions: "no Art. 50 duty" is a claim about
    five paragraphs at once, and the labels that were wrong were wrong in that direction. Same
    discipline as LegalSource on a verdict — a key that cannot show its working is how a wrong
    label survives unnoticed."""

    expected_abstains_at: str | None = None
    """WHICH cascade node the description runs out at. Set exactly when the class is NEEDS_REVIEW.

    That class says a run should decline; without this it does not say WHERE, and the two are not
    the same claim. A model that ducks a question it could have answered, and then happens to reach
    `needs_review`, is not doing what the case tests — it lands on the right label by the wrong
    route, and nothing could tell the difference.

    It also fixes what the case may pin. Once a node abstains the cascade stops, so every question
    after it is never put and must carry no expected answer; the loader enforces that against the
    graph's own routing. Held as a node_id rather than an article because the abstention is a fact
    about the RUN — which question went unanswered — not about the law."""

    decisive_fact: str  # the single fact that fixes the class (what a reader must catch)
    difficulty: Difficulty
    split: Split = "test"
    flips_from: str | None = None  # sibling case this one differs from by ~one sentence
    guidance_refs: list[str] = []  # Commission-guidance snippets backing this label —
    # "<doc-ref>/<slug>" ids into data/policy/guidance/. NON-BINDING interpretation, not law; used
    # where the enacted text alone leaves the label contestable. Resolved at load time (loader).
    notes: str | None = None

    @model_validator(mode="after")
    def _answer_key_is_legally_consistent(self) -> ClassificationCase:
        rc = self.expected_risk_class

        # Art. 50 — a claimed duty must name the paragraph it rests on. Not bureaucracy: the
        # labels this replaces were plain booleans with no recorded argument, and two of them were
        # simply wrong (Art. 50(3) expressly covers emotion recognition systems). The shipped answer
        # key argues the NEGATIVE too, which is stricter than this — enforced over the set itself
        # rather than here, so a synthetic test fixture need not carry the essay.
        if self.expected_transparency_duties and not self.transparency_basis.strip():
            raise ValueError(
                f"{self.case_id}: Art. 50 duties are claimed but transparency_basis is empty. Name "
                f"the paragraphs and why they attach."
            )

        # Art. 2 — an exclusion must name the paragraph it rests on, and nothing else may claim one.
        # The classes are ordered in law before the risk tiers: a system the Regulation does not
        # govern has no tier, so OUT_OF_SCOPE cannot carry Art. 6 sub-answers either.
        if (self.expected_scope_exclusion is not None) != (rc == RiskClass.OUT_OF_SCOPE):
            raise ValueError(
                f"{self.case_id}: expected_scope_exclusion={self.expected_scope_exclusion} but "
                f"expected_risk_class={rc}. An Art. 2 exclusion and the OUT_OF_SCOPE class are the "
                f"same fact stated two ways — the Regulation does not apply at all."
            )
        if self.expected_scope_exclusion is not None:
            if not self.scope_exclusion_basis.strip():
                raise ValueError(
                    f"{self.case_id}: an Art. 2 exclusion is claimed but scope_exclusion_basis is "
                    f"empty. Say why that paragraph applies."
                )
            if (
                self.expected_annex_iii_area is not None
                or self.expected_annex_i_product is not None
            ):
                raise ValueError(
                    f"{self.case_id}: Art. 6 classifies systems the Regulation governs. A system "
                    f"excluded by Art. 2 is never reached by it."
                )

        # NEEDS_REVIEW and an abstention point are the same claim stated two ways: the class says a
        # run should decline, this says where. Neither is usable without the other.
        if (self.expected_abstains_at is not None) != (rc == RiskClass.NEEDS_REVIEW):
            raise ValueError(
                f"{self.case_id}: expected_abstains_at={self.expected_abstains_at!r} but "
                f"expected_risk_class={rc}. Set it exactly when the class is needs_review — name "
                f"the node the description cannot answer."
            )

        # Art. 5 — a named point and the PROHIBITED class are the same fact, stated two ways. The
        # point is required rather than optional for the reason the Art. 2 basis is: this class
        # tells a provider their system may not ship, and a key asserting that without naming the
        # ban it rests on cannot be checked against the Article.
        if (self.expected_prohibited_practice is not None) != (rc == RiskClass.PROHIBITED):
            raise ValueError(
                f"{self.case_id}: expected_prohibited_practice="
                f"{self.expected_prohibited_practice} but expected_risk_class={rc}. Name the "
                f"Art. 5(1) point exactly when the class is PROHIBITED."
            )

        # Art. 6(3) profiling carve-back — mirror of classification.py: profiling => high_risk,
        # notwithstanding any derogation.
        if self.expected_performs_profiling is True:
            if rc != RiskClass.HIGH_RISK:
                raise ValueError(
                    f"{self.case_id}: performs_profiling is true, so the Art. 6(3) carve-back "
                    f"forces high_risk (got {rc})."
                )
            if self.expected_derogation is not None:
                raise ValueError(
                    f"{self.case_id}: performs_profiling is true, so no derogation can apply."
                )

        # Art. 6(1) — both conditions met is high_risk by the OTHER door, and the Art. 6(3)
        # derogations cannot reach it: they derogate from paragraph 2 alone.
        if self.expected_annex_i_product is not None and self.expected_third_party_assessment:
            if rc != RiskClass.HIGH_RISK:
                raise ValueError(
                    f"{self.case_id}: an Annex I product requiring third-party conformity "
                    f"assessment is high-risk under Art. 6(1) (got {rc})."
                )
            if self.expected_derogation is not None:
                raise ValueError(
                    f"{self.case_id}: Art. 6(3) derogates from Art. 6(2) only; it cannot apply to "
                    f"a system that is high-risk under Art. 6(1)."
                )
        if (
            self.expected_third_party_assessment is not None
            and self.expected_annex_i_product is None
        ):
            raise ValueError(
                f"{self.case_id}: expected_third_party_assessment is set but no Annex I product "
                f"is — condition (b) is only reached when (a) is met."
            )

        # Art. 6(3) exempts on BOTH limbs — a condition under (a)-(d) AND no significant risk of
        # harm — so a condition alone does not settle the class. Which way it lands is exactly what
        # the other limb decides, and the two `expected_poses_significant_risk` values are two
        # different cases: a `false` is the ordinary derogation, a `true` is a system that meets a
        # condition and is high-risk regardless.
        if self.expected_derogation is not None:
            if self.expected_poses_significant_risk is None:
                raise ValueError(
                    f"{self.case_id}: a derogation condition is named but "
                    f"expected_poses_significant_risk is not set. Art. 6(3) is a conjunction — the "
                    f"condition alone does not exempt anything."
                )
            expected = (
                RiskClass.HIGH_RISK
                if self.expected_poses_significant_risk
                else RiskClass.NOT_HIGH_RISK
            )
            if rc != expected:
                raise ValueError(
                    f"{self.case_id}: an Art. 6(3)(a)-(d) condition is met and "
                    f"expected_poses_significant_risk={self.expected_poses_significant_risk}, so "
                    f"expected_risk_class must be {expected} (got {rc})."
                )
        elif self.expected_poses_significant_risk is not None:
            raise ValueError(
                f"{self.case_id}: expected_poses_significant_risk is set but no derogation "
                f"condition is — the chapeau is only reached once one of (a)-(d) is met."
            )
        return self


class ClassificationGoldenSet(BaseModel):
    """The Layer 1 (classification) golden set."""

    act_version_date: str
    cases: list[ClassificationCase]

    def for_split(self, split: Split | Literal["all"]) -> list[ClassificationCase]:
        if split == "all":
            return list(self.cases)
        return [c for c in self.cases if c.split == split]
