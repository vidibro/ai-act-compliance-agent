"""EVAL ONLY — ground-truth cases for measuring the agent. Not part of the Regulation.

Two layers, because the agent does two different jobs:

  LAYER 1 — CLASSIFICATION (ClassificationCase). Given a use-case description, what RISK CLASS is
            it? prohibited / high_risk / not_high_risk / minimal. This is where the project's
            headline lives: the FLIP — a one-sentence edit that moves a use case from not_high_risk
            to high_risk via the Art. 6(3) profiling carve-back. Hand-authored: the description is
            the input, the class is known.

  LAYER 2 — OBLIGATION CHECKING (GoldenCase / GoldenSet). Given a high-risk system's documentation,
            does it satisfy each obligation? pass / gap / inadequate. Generated by degrading a
            known-compliant reference document in one known way, so ground truth is exact.

Layer 1 feeds the classification graph (M3); Layer 2 feeds the gap-analysis checker (M4). A case's
ground truth is never itself a judgement — it is fixed by construction (Layer 2) or by the author
stating the decisive fact and the class it forces (Layer 1).
"""

from __future__ import annotations

from enum import StrEnum
from typing import Literal

from pydantic import BaseModel, model_validator

from aiact.schemas.enums import (
    AnnexIIIArea,
    AnnexIProduct,
    DerogationCondition,
    RiskClass,
    Verdict,
)

# dev  = cases you may tune against (prompts, thresholds).
# test = HELD OUT. Never tuned against; the only split whose score you are allowed to report.
# Default is "test": a new case is protected from tuning until deliberately opted into dev, so you
# cannot silently overfit to it.
Split = Literal["dev", "test"]


class AblationType(StrEnum):
    """EVAL ONLY — not part of the Regulation. Describes how a requirement was degraded when
    generating a synthetic test document from the complete reference document. Because we know
    exactly what was altered, ground truth is exact."""

    REMOVED = "removed"
    """Section deleted outright. Expected verdict: GAP.
    NOTE: measured, not assumed. A realistic reference document cross-references itself, so
    deleting a section does not delete its topic words elsewhere — the keyword baseline scores
    1/7 here. Deletion is not the freebie it looks like."""

    PRESENT_BUT_INADEQUATE = "present_but_inadequate"
    """Section reduced to an empty assertion. Expected verdict: INADEQUATE.
    Defeats keyword matching — the most diagnostic class of example."""

    DISTRACTOR = "distractor"
    """Replaced with plausible-sounding but non-responsive content (e.g. a 'responsible AI'
    marketing section standing in for Art. 10 data governance). Expected verdict: GAP.
    Tests whether the agent distinguishes marketing from evidence of compliance.
    A false PASS here is the most dangerous failure mode of a compliance tool."""

    UNTOUCHED = "untouched"
    """Left intact. Expected verdict: PASS. Measures FALSE POSITIVES — a checker that flags
    everything is useless. Untouched requirements matter as much as ablated ones."""


class Difficulty(StrEnum):
    """EVAL ONLY. How hard the decisive fact is to locate in the input. Enables reporting
    accuracy per difficulty band instead of one meaningless aggregate number."""

    OBVIOUS = "obvious"
    """The decisive fact is stated plainly (e.g. 'returns a candidate fit score')."""

    BURIED = "buried"
    """The decisive fact is present but buried among features and vague marketing language.
    A drop in accuracy here means the agent is keyword-matching, not reading."""

    AMBIGUOUS = "ambiguous"
    """Genuinely contestable — reasonable experts could disagree. Reported separately;
    NEEDS_REVIEW is an acceptable answer here."""

    INSUFFICIENT = "insufficient"
    """The decisive fact is ABSENT. The law is clear and the experts would agree — the DESCRIPTION
    simply never says. Deliberately not folded into `ambiguous`: that band is about contested law,
    this one is about missing input, and averaging them would make both unreadable.

    NEEDS_REVIEW is the only correct answer here, and it is the band where a confident verdict is
    worst: silence is not evidence of absence, so reading 'the text never mentions ranking' as 'the
    system does not rank' hands a provider a derogation they never claimed and cannot support
    (Art. 6(3) puts the burden on establishing the condition; Art. 6(4) requires it documented)."""


class GoldenCase(BaseModel):
    """One synthetic document plus the verdict every applicable rule should receive."""

    case_id: str  # "AIA-HR-A14__present_but_inadequate"
    system_id: str  # which reference system this was generated from
    document_path: str  # repo-relative path to the generated case document
    raw_text: str  # the document itself, as the checker will see it
    ablated_rule_id: str | None  # None for the pristine (untouched) case
    ablation: AblationType
    difficulty: Difficulty
    split: Split = "test"  # dev = tunable; test = held out, the only reportable score
    expected: dict[str, Verdict]  # rule_id -> expected verdict, for ALL applicable rules

    @model_validator(mode="after")
    def _ablated_rule_is_expected(self) -> GoldenCase:
        """The degraded rule must appear in `expected` — otherwise the case measures nothing."""
        if self.ablated_rule_id is not None and self.ablated_rule_id not in self.expected:
            raise ValueError(
                f"{self.case_id}: ablated rule {self.ablated_rule_id!r} carries no "
                f"expected verdict."
            )
        if self.ablation == AblationType.UNTOUCHED and self.ablated_rule_id is not None:
            raise ValueError(
                f"{self.case_id}: an untouched case degrades nothing, so ablated_rule_id "
                f"must be None."
            )
        return self


class GoldenSet(BaseModel):
    """All cases generated from one reference document, for one act version."""

    system_id: str
    reference_path: str
    act_version_date: str
    spec_version: str
    cases: list[GoldenCase]

    def for_split(self, split: Split | Literal["all"]) -> list[GoldenCase]:
        """Cases in one split. Tune against `dev`; report only `test`."""
        if split == "all":
            return list(self.cases)
        return [c for c in self.cases if c.split == split]


# ==================================================================================================
# LAYER 1 — classification
# ==================================================================================================
class ClassificationCase(BaseModel):
    """One use-case description with its known risk class and the decisive sub-answers.

    The `description` is the ONLY input a classifier sees. Everything else is the answer key. The
    validators below re-enforce the same legal invariants the real classifier must obey
    (classification.py), so the ground truth cannot quietly contradict the law it measures."""

    case_id: str  # "cv_parsing_plus_scoring"
    description: str  # the use-case description the classifier reads — the input
    expected_risk_class: RiskClass

    # The "why" — the decisive sub-answers a correct classifier should also produce. Optional so a
    # case only pins what actually decides it.
    expected_scope_exclusion: str = ""
    """Art. 2 — WHICH paragraph puts this system outside the Regulation, and why. Mandatory whenever
    the class is OUT_OF_SCOPE, and forbidden otherwise (see the validator). Same discipline as
    `transparency_basis`: an exclusion that cannot name its paragraph is an assertion, and the
    exclusions are narrow enough ("exclusively" military, "sole purpose" of research) that the
    paragraph is where the argument actually lives."""

    expected_prohibited: bool = False  # Art. 5
    expected_annex_i_product: AnnexIProduct | None = None
    """Art. 6(1)(a) — the product family whose safety component this system is, or None."""

    expected_third_party_assessment: bool | None = None
    """Art. 6(1)(b) — whether that product needs a notified body. Art. 6(1) is a CONJUNCTION, so a
    case that sets the product without this pins only half the test."""

    expected_annex_iii_area: AnnexIIIArea | None = None  # Art. 6(2), Annex III
    expected_performs_profiling: bool | None = None  # Art. 6(3) carve-back
    expected_derogation: DerogationCondition | None = None  # Art. 6(3)(a)-(d)
    expected_transparency_obligation: bool = False
    """Art. 50 — applies regardless of the risk tier.

    SCOPE: TRUE means **any** Art. 50 obligation attaches to this system, whether it falls on the
    provider or on the deployer. Art. 50 is titled
    "Transparency obligations for providers AND deployers" and the paragraphs split by role —
    (1) direct interaction and (2) marking synthetic output bind the PROVIDER; (3) emotion
    recognition / biometric categorisation and (4) deep fakes bind the DEPLOYER. A provider report
    that stayed silent about a duty its deployers will certainly owe would be less useful, not more
    rigorous, so both count — and `transparency_basis` records which paragraph, so the label stays
    arguable instead of asserted."""

    transparency_basis: str = ""
    """WHICH Art. 50 paragraph attaches, and why. Mandatory whenever the obligation is TRUE (see the
    validator). Same discipline as LegalSource on a verdict: an answer key that cannot show its
    working is how a wrong label survives — this one did, until the smoke check tripped over it."""

    decisive_fact: str  # the single fact that fixes the class (what a reader must catch)
    difficulty: Difficulty
    split: Split = "test"
    flips_from: str | None = None  # sibling case this one differs from by ~one sentence
    guidance_refs: list[str] = []  # Commission-guidance snippets backing this label —
    # "<doc-ref>/<slug>" ids into data/policy/guidance/. NON-BINDING interpretation, not law; used
    # where the enacted text alone leaves the label contestable. Resolved at load time (loader).
    notes: str | None = None

    @model_validator(mode="after")
    def _answer_key_is_legally_consistent(self) -> ClassificationCase:
        rc = self.expected_risk_class

        # Art. 50 — a claimed transparency obligation must name the paragraph it rests on. Not
        # bureaucracy: the labels this replaces were plain booleans with no recorded argument, and
        # two of them were simply wrong (Art. 50(3) expressly covers emotion recognition systems).
        if self.expected_transparency_obligation and not self.transparency_basis.strip():
            raise ValueError(
                f"{self.case_id}: expected_transparency_obligation=True but transparency_basis is "
                f"empty. Name the Art. 50 paragraph and why it attaches."
            )

        # Art. 2 — an exclusion must name the paragraph it rests on, and nothing else may claim one.
        # The classes are ordered in law before the risk tiers: a system the Regulation does not
        # govern has no tier, so OUT_OF_SCOPE cannot carry Art. 6 sub-answers either.
        if rc == RiskClass.OUT_OF_SCOPE:
            if not self.expected_scope_exclusion.strip():
                raise ValueError(
                    f"{self.case_id}: expected_risk_class=out_of_scope but "
                    f"expected_scope_exclusion is empty. Name the Art. 2 paragraph and why it "
                    f"applies."
                )
            if (
                self.expected_annex_iii_area is not None
                or self.expected_annex_i_product is not None
            ):
                raise ValueError(
                    f"{self.case_id}: Art. 6 classifies systems the Regulation governs. A system "
                    f"excluded by Art. 2 is never reached by it."
                )
        elif self.expected_scope_exclusion.strip():
            raise ValueError(
                f"{self.case_id}: expected_scope_exclusion is set but expected_risk_class={rc}. "
                f"An Art. 2 exclusion means the Regulation does not apply at all."
            )

        # Art. 5 — prohibition and the PROHIBITED class are the same fact, stated two ways.
        if self.expected_prohibited != (rc == RiskClass.PROHIBITED):
            raise ValueError(
                f"{self.case_id}: expected_prohibited={self.expected_prohibited} but "
                f"expected_risk_class={rc}. A prohibited practice is exactly the PROHIBITED class."
            )

        # Art. 6(3) profiling carve-back — mirror of classification.py: profiling => high_risk,
        # notwithstanding any derogation.
        if self.expected_performs_profiling is True:
            if rc != RiskClass.HIGH_RISK:
                raise ValueError(
                    f"{self.case_id}: performs_profiling is true, so the Art. 6(3) carve-back "
                    f"forces high_risk (got {rc})."
                )
            if self.expected_derogation is not None:
                raise ValueError(
                    f"{self.case_id}: performs_profiling is true, so no derogation can apply."
                )

        # Art. 6(1) — both conditions met is high_risk by the OTHER door, and the Art. 6(3)
        # derogations cannot reach it: they derogate from paragraph 2 alone.
        if self.expected_annex_i_product is not None and self.expected_third_party_assessment:
            if rc != RiskClass.HIGH_RISK:
                raise ValueError(
                    f"{self.case_id}: an Annex I product requiring third-party conformity "
                    f"assessment is high-risk under Art. 6(1) (got {rc})."
                )
            if self.expected_derogation is not None:
                raise ValueError(
                    f"{self.case_id}: Art. 6(3) derogates from Art. 6(2) only; it cannot apply to "
                    f"a system that is high-risk under Art. 6(1)."
                )
        if (
            self.expected_third_party_assessment is not None
            and self.expected_annex_i_product is None
        ):
            raise ValueError(
                f"{self.case_id}: expected_third_party_assessment is set but no Annex I product "
                f"is — condition (b) is only reached when (a) is met."
            )

        # A derogation is the REASON a use case escapes high-risk — so it implies not_high_risk.
        if self.expected_derogation is not None and rc != RiskClass.NOT_HIGH_RISK:
            raise ValueError(
                f"{self.case_id}: a derogation applies, so expected_risk_class must be "
                f"not_high_risk (got {rc})."
            )
        return self


class ClassificationGoldenSet(BaseModel):
    """The Layer 1 (classification) golden set."""

    act_version_date: str
    cases: list[ClassificationCase]

    def for_split(self, split: Split | Literal["all"]) -> list[ClassificationCase]:
        if split == "all":
            return list(self.cases)
        return [c for c in self.cases if c.split == split]
