# Modelled on the European Commission's own wording for their AI Act Compliance Checker, with a
# second paragraph this tool owes its own users: Art. 6(1) settles a system's risk class by
# reference to twenty OTHER instruments, so some answers are not answerable from the AI Act alone
# and a legal reviewer is not always the right reviewer.
DISCLAIMER = (
    "This report is generated by an automated tool and is provided for informational purposes "
    "only. It does not constitute legal advice, and it does not represent the assessment or "
    "official position of the European Commission or any other authority. The classification "
    "and findings may be incomplete or incorrect. You should consult a qualified legal "
    "professional before relying on any part of this report.\n\n"
    "Some questions the Regulation asks cannot be answered from the Regulation alone. Where an AI "
    "system is part of a regulated product — a medical device, machinery, a vehicle, and other "
    "categories listed in Annex I — its risk class depends on rules in that product's own "
    "legislation, which this tool does not apply. Those questions need a specialist in that "
    "sector, not only a lawyer. This tool does not attempt them: it reports what the "
    "documentation states, says when the answer is missing, and leaves the question open rather "
    "than guessing. An open question is unfinished work, not a clean result.\n\n"
    "Roles can change hands, and where a system is high-risk this report asks whether they have. "
    "Under Article 25 a distributor, importer, deployer or other third party BECOMES the provider "
    "where it puts its name on a high-risk system someone else placed on the market, substantially "
    "modifies one, or changes the intended purpose of a system so that it becomes high-risk; under "
    "Article 25(3) a product manufacturer placing an AI system on the market with its own product "
    "is the provider of it. That question is answered from what the documentation states about who "
    "placed the system on the market and what any later party does to it. A document written from "
    "a single party's point of view usually shows neither, so silence is not a finding that "
    "Article 25 moved nothing. Any organisation to which one of those circumstances applies owes "
    "the provider obligations set out in this report, whatever role the documentation gives it."
)

def _systemic_risk_note(risk: SystemicRisk | None) -> str:
    """What the Art. 51 answer settles, in the reader's own terms."""
    if risk is SystemicRisk.DESIGNATED:
        return (
            "SYSTEMIC RISK IS ESTABLISHED on the face of the documentation — it records a "
            "Commission designation or an Art. 52(1) notification. The Art. 55 obligations below "
            "are owed in addition to Arts. 53 and 54, and Art. 52(5) allows a reasoned request for "
            "reassessment at the earliest six months after the designation decision."
        )
    if risk is SystemicRisk.HIGH_IMPACT_CAPABILITIES:
        return (
            "SYSTEMIC RISK IS PRESUMED: the documentation states cumulative training compute above "
            "10^25 floating point operations, which Art. 51(2) presumes to be the high impact "
            "capabilities of Art. 51(1)(a). The Art. 55 obligations below are owed, and Art. 52(1) "
            "requires the Commission to be notified within two weeks of the threshold being met or "
            "foreseen. The presumption is rebuttable — Art. 52(2) allows substantiated arguments "
            "that the model presents no systemic risk despite meeting the condition — but the "
            "arguments travel WITH the notification, not instead of it."
        )
    if risk is SystemicRisk.BELOW_THRESHOLD:
        return (
            "The documentation states cumulative training compute BELOW 10^25 floating point "
            "operations, so the Art. 51(2) presumption is not engaged on the stated figure. THAT "
            "DEFEATS THE PRESUMPTION AND NOT THE CONDITION. Art. 51(2) runs one way only: above "
            "the threshold high impact capabilities are presumed, below it nothing is presumed "
            "either way, and Art. 51(1)(a) remains a substantive test of capabilities evaluated "
            "on appropriate technical tools and methodologies, which says nothing about compute. "
            "Art. 51(1)(b) then lets the Commission designate a model on the Annex XIII criteria "
            "at any level of compute at all. So this figure does not establish that the model is "
            "outside Art. 51(1); the Art. 52(6) list of models with systemic risk is where the "
            "question is settled. The Art. 55 obligations are still listed below."
        )
    return (
        "The documentation states neither a Commission designation nor a cumulative training "
        "compute figure, so whether Art. 51(1) reaches this model is UNANSWERED — not answered no. "
        "This tool does not estimate compute from a parameter count. The Art. 55 obligations are "
        "listed below with that condition attached; the Art. 52(6) list of models with systemic "
        "risk is where the question is actually settled."
    )


def _release_note(risk: SystemicRisk | None, release: OpenSourceRelease | None) -> str:
    """What the Art. 53(2)/54(6) answer settles, READ WITH the Art. 51 answer.

    Never alone: both carve-outs are disapplied for a model with systemic risk, so a fully open
    release lifts nothing while Art. 51 is answered yes or left open."""
    if release is None:
        return ""
    if release is OpenSourceRelease.FULLY_OPEN:
        if risk is not None and risk.carries_systemic_risk:
            return (
                "The release is described as meeting the Art. 53(2) open-source conditions, and "
                "both that carve-out and Art. 54(6) are DISAPPLIED for a general-purpose AI model "
                "with systemic risk under Art. 51(1) — which the answer above establishes. So the "
                "licence lifts nothing here: Art. 53(1)(a) and (b) and the whole of Art. 54 stand."
            )
        # THE CARVE-OUT IS NEVER APPLIED, ONLY REPORTED AS AVAILABLE. Both Art. 53(2) and
        # Art. 54(6) are disapplied for a model with systemic risk, and no document settles
        # Art. 51(1) in the negative — `carries_systemic_risk` is True or None and never False.
        # So the most this tool can say is that the licence half is answered and the Art. 51 half
        # is not. Saying the obligations are lifted would clear the Annex XI documentation, the
        # Annex XII downstream information and the whole of Art. 54 on a condition nobody checked.
        return (
            "The release is described as meeting all four Art. 53(2) conditions — a free and "
            "open-source licence allowing access, use, modification and distribution, with the "
            "parameters, architecture information and usage information publicly available. THAT "
            "IS ONE HALF OF THE CARVE-OUT AND NOT THE WHOLE OF IT: both Art. 53(2) and Art. 54(6) "
            "are disapplied for a general-purpose AI model with systemic risk, and the Art. 51 "
            "answer above does not establish that this model is outside Art. 51(1). If it is, "
            "Art. 53(2) lifts Art. 53(1)(a) and (b) and Art. 54(6) lifts the whole of Art. 54 — "
            "and Art. 53(1)(c) and (d), the copyright policy and the public training-content "
            "summary, are not lifted by either and are owed by every provider whatever its "
            "licence. All of them are listed below, on that condition, because this report does "
            "not decide it."
        )
    if release is OpenSourceRelease.NOT_OPEN:
        return (
            "The release does NOT meet the Art. 53(2) conditions — at least one of the licence "
            "terms or the public availability of the parameters, architecture information and "
            "usage information fails. Neither carve-out is available, so Art. 53(1)(a) and (b) and "
            "the whole of Art. 54 are owed in full."
        )
    return (
        "The documentation does not say enough about the licence and the released artefacts to "
        "decide the Art. 53(2) carve-out, which has to be earned on ALL FOUR of its limbs. Silence "
        "on any of them leaves Art. 53(1)(a) and (b) and the whole of Art. 54 standing."
    )


_FAILING = (Verdict.GAP, Verdict.INADEQUATE)


class CriterionFinding(BaseModel):
    """The verdict on one criterion of an aggregate rule, named by its norm."""

    norm_id: str
    mandatory: bool
    verdict: Verdict
    reasoning: str
    evidence_quote: str | None = None
    evidence_chunk_id: str | None = None
    confidence: Confidence

    @model_validator(mode="after")
    def _accusation_needs_reasoning(self) -> CriterionFinding:
        if self.verdict in _FAILING and not self.reasoning.strip():
            raise ValueError(
                f"Criterion {self.norm_id}: verdict={self.verdict} requires non-empty reasoning."
            )
        if len(self.evidence_quote or "") > EVIDENCE_QUOTE_MAX:
            raise ValueError(f"Criterion {self.norm_id}: evidence_quote exceeds the quote cap.")
        return self


def aggregate_criteria(criteria: list[CriterionFinding]) -> Verdict:
    """The rule verdict its criteria allow. Only mandatory criteria count, and none is outvoted.

      any gap or inadequate  -> failing: GAP when no mandatory criterion was addressed at all
                                (none passed or was thin), otherwise INADEQUATE — the rule's
                                content exists and falls short
      else any needs_review  -> NEEDS_REVIEW
      all pass               -> PASS
      all not_applicable     -> NOT_APPLICABLE (the rule was not judged)
      pass mixed with n/a    -> NEEDS_REVIEW: a mandatory criterion went unjudged"""
    verdicts = [criterion.verdict for criterion in criteria if criterion.mandatory]
    if not verdicts:
        raise ValueError("an aggregate rule needs at least one mandatory criterion")
    if any(verdict in _FAILING for verdict in verdicts):
        addressed = any(verdict in (Verdict.PASS, Verdict.INADEQUATE) for verdict in verdicts)
        return Verdict.INADEQUATE if addressed else Verdict.GAP
    if Verdict.NEEDS_REVIEW in verdicts:
        return Verdict.NEEDS_REVIEW
    if all(verdict is Verdict.PASS for verdict in verdicts):
        return Verdict.PASS
    if all(verdict is Verdict.NOT_APPLICABLE for verdict in verdicts):
        return Verdict.NOT_APPLICABLE
    return Verdict.NEEDS_REVIEW


class Finding(BaseModel):
    """The verdict on one PolicyRule for one use case.

    `citation` is a required LegalSource with no default: an uncited finding cannot be built.
    `rule_id` is kept as a plain id rather than the full rule — the rule already lives in the
    loaded PolicyRuleset, and embedding it here would duplicate every rule in every report."""

    rule_id: str  # references PolicyRule.rule_id in the loaded PolicyRuleset
    use_case_id: str  # which use case activated this rule
    role: ActorRole
    """WHOSE obligation this is. REQUIRED, with no default, for the same reason `citation` has
    none: a finding that cannot say whose duty it is would quietly become the provider's, and a
    deployer duty mis-attributed that way is worse than one left out — the provider cannot
    discharge it and will not know that.

    Art. 4 binds both roles, so the same rule can produce a finding for each — different duties
    held by different parties, and a report that could not tell them apart would report one of
    them twice and neither correctly."""

    verdict: Verdict
    evidence_quote: str | None = None
    evidence_chunk_id: str | None = None
    reasoning: str
    citation: LegalSource
    confidence: Confidence

    guidance: list[GuidanceSource] = []
    """NON-BINDING Commission interpretation the judge was shown when reaching this verdict.

    Separate from `citation`, which is enacted law, and never merged with it — the same split
    `ClassificationEvidence` keeps one layer up. A finding reached with the Commission's reading in
    front of the judge is weaker than one resting on the Article alone, and a reader who cannot see
    which is which cannot weigh it. Empty for almost every finding, which is what makes the
    non-empty ones worth noticing."""

    criteria: list[CriterionFinding] = []
    """One verdict per criterion of an aggregate rule, in the rule's order. Empty for a rule
    judged as one obligation. When present, `verdict` must be what `aggregate_criteria` computes
    from them, so a report cannot hold a passing rule over a failing criterion."""

    @property
    def rests_on_guidance(self) -> bool:
        """True when non-binding interpretation was in context for this verdict."""
        return bool(self.guidance)

    @model_validator(mode="after")
    def _aggregate_matches_its_criteria(self) -> Finding:
        if not self.criteria:
            return self
        ids = [criterion.norm_id for criterion in self.criteria]
        if len(ids) != len(set(ids)):
            raise ValueError(f"Finding for rule {self.rule_id!r}: a criterion is reported twice.")
        expected = aggregate_criteria(self.criteria)
        if self.verdict is not expected:
            raise ValueError(
                f"Finding for rule {self.rule_id!r}: verdict={self.verdict} but its criteria "
                f"aggregate to {expected}."
            )
        return self

    @field_validator("evidence_quote")
    @classmethod
    def _evidence_quote_is_a_quote(cls, v: str | None) -> str | None:
        if v is not None and len(v) > EVIDENCE_QUOTE_MAX:
            raise ValueError(
                f"evidence_quote must be under {EVIDENCE_QUOTE_MAX} chars "
                f"(got {len(v)}) — cite a pinpoint excerpt, do not dump a section."
            )
        return v

    @field_validator("reasoning")
    @classmethod
    def _reasoning_is_one_sentence(cls, v: str) -> str:
        """clip_reasoning() it at the call site."""
        if len(v) > REASONING_MAX:
            raise ValueError(f"reasoning must be under {REASONING_MAX} chars (got {len(v)}).")
        return v

    @model_validator(mode="after")
    def _gap_and_inadequate_need_reasoning(self) -> Finding:
        """A GAP or INADEQUATE verdict is an accusation; it must justify itself."""
        if self.verdict in (Verdict.GAP, Verdict.INADEQUATE) and not self.reasoning.strip():
            raise ValueError(
                f"Finding for rule {self.rule_id!r}: verdict={self.verdict} requires "
                f"non-empty reasoning."
            )
        return self


class ReportSummary(BaseModel):
    """Verdict tallies, optionally broken down per use case."""

    total_applicable: int
    passed: int
    gaps: int
    inadequate: int
    needs_review: int
    per_use_case: dict[str, ReportSummary] | None = None  # counts broken down per use case
    per_role: dict[ActorRole, ReportSummary] | None = None
    """Counts broken down per duty-holder. A provider reading a combined total cannot tell which
    part of it is theirs to fix, and the deployer's half is not theirs to fix at all."""


class ComplianceReport(BaseModel):
    """The full assembled output for one SystemUnderReview against one PolicyRuleset."""

    system_id: str
    act_version_date: date
    spec_version: str
    generated_at: datetime
    classification: ClassificationResult
    findings: list[Finding]
    not_document_verifiable: dict[ActorRole, list[str]] = {}
    """Rule ids to confirm separately, keyed by WHO owes them — NOT gaps.

    Grouped by role because that is the only way the list is actionable: a provider cannot confirm
    that a deployer informed its workers under Art. 26(7).
    Roles owing nothing are absent rather than present-and-empty.

    AN INDEX, NOT THE OBLIGATION. These rules never reach the judge, so unlike a `Finding` they
    carry no reasoning of their own, and an id alone tells a reader nothing they can act on — which
    members of the role owe it, from when, and what would satisfy it all live on the rule in the
    spec. `aiact.reporting.render_report` resolves each id and renders those beside it; any other
    consumer must do the same, and `tests/test_reporting.py` holds the shipped renderer to it."""

    permissions: dict[ActorRole, list[str]] = {}
    """Canonical permission norm ids, keyed by the active duty-holder role.

    These are allowed implementation routes, not a conclusion that the reader has used one.  They
    are separate from findings so a permission can never make an obligation pass or fail.
    """

    legal_consequences: dict[ActorRole, list[str]] = {}
    """Canonical legal-effect norm ids, keyed by the active duty-holder role.

    This includes conditional deeming and reliefs.  The renderer shows their conditions and
    exceptions; the product does not decide that a reader qualifies from silence in a document.
    """

    conditional_applicability: dict[ActorRole, list[str]] = {}
    """Canonical applicability norm ids, keyed by the active duty-holder role.

    These state a condition that narrows a rule's scope. They are shown without a verdict: silence
    in a document does not prove the condition applies. Keeping them outside findings prevents a
    scope limit from changing the verdict of the obligations it limits.
    """

    deployer_type: Answer | None = None
    """What kind of organisation deploys the system — read from the documentation, where it says.

    Several deployer duties are narrowed by this and Art. 27 is the one modelled: the fundamental
    rights impact assessment binds deployers that are bodies governed by public law or private
    entities providing public services. The obligation is listed under the deployer whatever this
    answers; the answer only tells a reader which side of that condition the document falls on,
    which is otherwise a paragraph of prose the report restates and never resolves.

    `None` means the question was not put — it is asked for a high-risk Annex III system, because
    no other classification carries a duty narrowed this way."""

    real_world_testing: Answer | None = None
    """Art. 60 — whether the documentation says the system is TESTED IN REAL WORLD CONDITIONS
    outside a sandbox before it is placed on the market.

    The one answer here that can WITHHOLD obligations, and the report says so rather than letting
    four obligations appear and disappear silently. `RealWorldTesting.NONE` — a document that
    positively establishes there is no such trial — drops Art. 60(4)'s conditions, Art. 60(7),
    Art. 60(8) and Art. 61. Every other answer, silence included, leaves them listed with their
    condition attached.

    `None` means the question was not put, because the system is not high-risk and Art. 60 governs
    no other tier."""

    provider_reallocation: Answer | None = None
    """Art. 25 — whether the reader has BECOME the provider of a system someone else built.

    A statement about WHOSE the findings above are, which is why it sits on the report rather than
    on the classification: the tier is a fact about the system, this is a fact about the reader.
    `None` means the question was not put — Art. 25 reallocates the provider of a high-risk system
    and of nothing else — which is not the same as an answer of "nobody was reallocated"."""

    summary: ReportSummary
    scope_note: str | None = None
    """Why the obligation check covered what it did — set whenever `findings` is empty for a reason
    a reader would otherwise have to infer. An empty findings list reads as a clean bill of health,
    and for a prohibited practice or an out-of-scope system that reading is dangerously wrong."""
    disclaimer: str = DISCLAIMER

    @property
    def guidance_sources(self) -> list[GuidanceSource]:
        """Every non-binding Commission passage this report leaned on, de-duplicated by snippet_ref
        and covering BOTH halves — the classification's and the obligation check's.

        Both, because a reader asking "how much of this rests on interpretation rather than enacted
        law?" is asking about the report, and a rollup that covered only the half it was written for
        would answer confidently and wrongly."""
        seen = {g.snippet_ref: g for g in self.classification.guidance_sources}
        for finding in self.findings:
            for g in finding.guidance:
                seen.setdefault(g.snippet_ref, g)
        return list(seen.values())

    @property
    def rests_on_guidance(self) -> bool:
        """True where any verdict in this report had Commission interpretation in front of it."""
        return bool(self.guidance_sources)

    @property
    def legacy_system_note(self) -> str | None:
        """Art. 111 — what changes if the system was ALREADY on the market. Reported, never applied.

        THE FACT IT TURNS ON IS ONE NOTHING HERE READS: the date the system was placed on the
        market or put into service. Same shape as Art. 6(1)(b) and Art. 2(4) — a condition to read,
        never to derive — so no obligation above is withheld on it, and the counts are unchanged.

        The direction of the error is why it is reported this way round. Art. 111(2) is RELIEF: it
        can remove obligations rather than add them, so guessing it wrong clears a reader who is not
        cleared, and this report would look like a pass. Naming it instead over-reports, which costs
        the reader a conversation with their adviser rather than a breach.

        Three limbs, because the Article gives three different reliefs and a reader told about one
        would carry it across to the others. 111(2) is about Chapter III whole; 111(3) is about
        Chapter V and reaches a general-purpose model rather than a system; 111(4) is about
        Art. 50(2) alone, and it is the tighter deadline of the three. 111(1) is not here: it is
        about components of the Annex X large-scale IT systems, which this tool does not assess.

        No limb fires for every report and 111(3) fires for the reports the others cannot reach —
        `_article_111_2_note` returns None where no use case is high-risk, which is always true of
        a model, so without this limb the one reader Art. 111(3) is written for got no note at
        all."""
        limbs = [
            self._article_111_2_note(),
            self._article_111_3_note(),
            self._article_111_4_note(),
        ]
        written = [limb for limb in limbs if limb]
        return " ".join(written) if written else None

    def _article_111_2_note(self) -> str | None:
        """The Chapter III limb, worded around the route because Art. 113(c) dates the two apart.

        Art. 113(c) keys on the classification, not on the product: (i) gives 2 December 2027 to a
        system "classified as high-risk pursuant to Article 6(2) and Annex III", (ii) 2 August 2028
        to one "classified as high-risk pursuant to Article 6(1) and Annex I". A named product that
        self-assesses is classified under 6(2), so it takes the earlier date — reading the product
        alone would hand it eight months of relief the Article does not give.

        ALL, not ANY, across the use cases. Risk is classified per use case, so one system can hold
        an Art. 6(1) use case and an Annex III use case at once and the two have different dates.
        The later date is right only where EVERY high-risk use case earned it; `any` would print
        2 August 2028 over a use case bound from 2 December 2027. Art. 111(2) is relief, so the
        generous reading is the one that clears a reader who is not cleared."""
        high_risk = [
            uc for uc in self.classification.use_cases if uc.risk_class == RiskClass.HIGH_RISK
        ]
        if not high_risk:
            return None
        annex_i = all(uc.high_risk_under_article_6_1 for uc in high_risk)
        applies_from = "2 August 2028" if annex_i else "2 December 2027"
        return (
            f"IF THIS SYSTEM WAS ALREADY ON THE MARKET, some of the above may not bind it yet. "
            f"Chapter III applies from {applies_from} (Art. 113(c)), and under Art. 111(2) a "
            f"high-risk system placed on the market or put into service before that date is "
            f"reached only once it undergoes significant changes in its design. Three things that "
            f"relief does NOT cover: the Art. 5 prohibitions, which apply to a legacy system "
            f"regardless; a system intended to be used by public authorities, whose providers and "
            f"deployers must comply by 2 August 2030 in any case; and anything this report raises "
            f"outside Chapter III. Whether the system is already on the market is not stated in "
            f"the documentation reviewed, so nothing here has been withheld on it — take advice "
            f"before relying on Art. 111(2)."
        )

    def _article_111_3_note(self) -> str | None:
        """The Chapter V limb, and the only one that fires on a general-purpose AI MODEL.

        The relief is a DEFERRAL rather than a carve-out: a model placed on the market before
        2 August 2025 owes everything the AIA-GP-* rules carry and owes it by 2 August 2027. That
        is the one date in this ruleset later than the obligation it defers, which is why it is
        worth saying out loud — every Chapter V rule below carries `effective_date: 2025-08-02`,
        and a provider reading that date against a model it shipped in 2024 would conclude it is
        two years in breach."""
        if not any(
            uc.risk_class is RiskClass.GPAI_MODEL for uc in self.classification.use_cases
        ):
            return None
        return (
            "IF THIS MODEL WAS PLACED ON THE MARKET BEFORE 2 AUGUST 2025, the Chapter V dates "
            "above are not the ones that bind it. Art. 111(3) gives the provider of such a model "
            "until 2 AUGUST 2027 to take the necessary steps to comply with the obligations laid "
            "down in this Regulation — a deferral of the duties listed below, not a release from "
            "any of them. Every Chapter V obligation here carries 2 August 2025, the date "
            "Art. 113(b) gives the Chapter, which is the date for a model placed on or after it. "
            "When the model was placed on the market is not stated in the documentation reviewed, "
            "so nothing here has been withheld on it — take advice before relying on Art. 111(3)."
        )

    def _article_111_4_note(self) -> str | None:
        """The Art. 50(2) limb. Fires on the DUTY rather than the tier, as Art. 50 always does."""
        duties = self.classification.transparency_duties
        if TransparencyDuty.SYNTHETIC_CONTENT_MARKING not in duties:
            return None
        return (
            "For the Art. 50(2) marking duty specifically, Art. 111(4) gives a system placed on "
            "the market before 2 August 2026 until 2 December 2026 to comply — later than the "
            "date this report carries, which is the one for a system placed after it."
        )

    @property
    def deployer_organisation(self) -> DeployerType | None:
        """The kind of organisation the documentation describes as deploying, or None where the
        question was not put or the answer was unusable. Narrowed by TYPE, as elsewhere."""
        answer = self.deployer_type
        value = answer.value if answer is not None else None
        return value if isinstance(value, DeployerType) else None

    @property
    def chapter_v_gate_note(self) -> str | None:
        """WHICH SIDE OF CHAPTER V'S TWO LINES this document falls on, or None for anything that is
        not a general-purpose AI model.

        The report lists every Chapter V obligation for every model, because neither line is a fact
        a model card reliably settles and withholding four duties on a guess would be a clearance.
        This is the other half of that bargain: the reader is told what their own document says, so
        a card that states a designation or a compute figure gets an answer rather than the
        condition read back at them.

        BOTH LINES IN ONE NOTE, because neither decides anything alone. Art. 53(2) lifts
        Art. 53(1)(a) and (b), and Art. 54(6) lifts the whole of Art. 54 — but both are disapplied
        for a model with systemic risk, so a fully open release lifts nothing until Art. 51 is
        answered. A reader told only about the licence would draw exactly the wrong conclusion."""
        risk = self.classification.stated_systemic_risk
        release = self.classification.stated_open_source_release
        if risk is None and release is None:
            return None
        return " ".join(p for p in (_systemic_risk_note(risk), _release_note(risk, release)) if p)

    @property
    def real_world_testing_note(self) -> str | None:
        """What the Art. 60 answer settled, or None where the question was not put.

        THE ONLY NOTE ATTACHED TO A WITHHOLDING, which is why it exists at all. Every other answer
        in this report resolves a condition on an obligation that is listed either way; this one
        decides whether four obligations are listed. A reader who is not told which way it went
        cannot tell a system that cleared Art. 60 from one nobody asked about, and the difference
        is the whole of Arts. 60 and 61."""
        answer = self.real_world_testing
        value = answer.value if answer is not None else None
        if not isinstance(value, RealWorldTesting):
            return None
        if value is RealWorldTesting.NONE:
            return (
                "Art. 60: this documentation states that the system is not tested in real world "
                "conditions outside an AI regulatory sandbox, so the pre-market testing duties of "
                "Art. 60(4), (7) and (8) and the informed consent of Art. 61 are NOT listed below. "
                "If a live trial is planned after all, they bind before it starts — the testing "
                "plan has to be submitted and approved and the testing registered first."
            )
        if value is RealWorldTesting.NOT_STATED:
            return (
                "Art. 60: this documentation does not say whether the system is tested in real "
                "world conditions outside a sandbox, so the duties that route carries are listed "
                "below with their condition attached. A provider that runs no such trial owes none "
                "of them and can dismiss them in one reading."
            )
        return (
            f"Art. 60: this documentation states that testing in real world conditions is "
            f"{value.value}, so the duties of Art. 60(4), (7) and (8) and the informed consent of "
            f"Art. 61 are listed below and bind BEFORE the testing starts."
        )

    @property
    def deployer_type_note(self) -> str | None:
        """What the answer settles, or None where nothing was asked.

        TWO duties turn on this one fact and they do not answer alike, which is why the note is
        composed rather than written once. Art. 27 reaches bodies governed by public law AND private
        entities providing public services; Art. 49(3) reaches public authorities and Union bodies
        only. A private entity providing public services owes the impact assessment and not the
        registration, and a reader who was told about one would reasonably assume the other."""
        art_27 = self._article_27_note()
        if art_27 is None:
            return None
        return f"{art_27} {self._article_49_3_note()}"

    def _article_49_3_note(self) -> str:
        """What the answer settles about Art. 49(3)'s deployer registration.

        The `False` branch is narrower than a bare "does not reach you", and says so: "persons
        acting on their behalf" can catch a private organisation running a system FOR a public
        authority, and no description of the organisation's own type establishes that relationship.
        """
        kind = self.deployer_organisation
        caught = kind.caught_by_article_49_3 if kind is not None else None
        if caught is True:
            return (
                "Art. 49(3) reaches it too: a public authority must register ITSELF, select the "
                "system and register its use in the EU database before putting the system into "
                "service — a separate entry from the provider's registration under Art. 49(1), "
                "which does not discharge it."
            )
        if caught is False:
            return (
                "Art. 49(3) is narrower and does not reach it on that basis: deployer registration "
                "binds public authorities and Union bodies, and a private entity is not one by "
                "providing public services. It can still be caught as a person acting on a public "
                "authority's behalf — a fact about the arrangement rather than the organisation, "
                "which nothing here establishes."
            )
        return (
            "The same silence leaves Art. 49(3) unresolved, and it is a narrower question: "
            "deployer registration binds public authorities, Union bodies, and persons acting on "
            "their behalf."
        )

    def _article_27_note(self) -> str | None:
        """What the answer settles about Art. 27's organisation limb, or None where nothing was
        asked. Three outcomes, and the third is not the second: a document that does not say is not
        a document describing a private commercial deployer."""
        kind = self.deployer_organisation
        if kind is None:
            return None
        caught = kind.caught_by_article_27
        if caught is True:
            which = (
                "a body governed by public law"
                if kind is DeployerType.PUBLIC_BODY
                else "a private entity providing public services"
            )
            return (
                f"The documentation describes the deployer as {which}, which Art. 27(1) reaches. "
                f"The fundamental rights impact assessment is owed before the system is first put "
                f"into use, and its result notified to the market surveillance authority "
                f"(Art. 27(3))."
            )
        if caught is False:
            return (
                "The documentation describes an ordinary commercial deployer, which Art. 27(1)'s "
                "first limb does not reach. The second limb still can: the assessment is owed by "
                "any deployer of an Annex III(5)(b) system — creditworthiness or credit scoring — "
                "or an Annex III(5)(c) one — risk assessment and pricing for life and health "
                "insurance — whoever they are, and this ruleset classifies by listed area rather "
                "than by those sub-points."
            )
        return (
            "The documentation does not say what kind of organisation deploys the system, so "
            "whether Art. 27(1) reaches it is unresolved. That is not a finding that it does not: "
            "the paragraph reaches bodies governed by public law and private entities providing "
            "public services, and one line naming the deployer would settle it either way."
        )

    @property
    def becomes_provider(self) -> ProviderReallocation | None:
        """The Art. 25 limb that made the reader the provider, or None.

        Narrowed by TYPE for the reason the cascade's own helpers are: only a recognised member is
        a finding that can be cited, and a reallocation nobody can cite is one the reader cannot
        check or contest."""
        answer = self.provider_reallocation
        value = answer.value if answer is not None else None
        return value if isinstance(value, ProviderReallocation) else None

    @property
    def provider_reallocation_note(self) -> str | None:
        """What an Art. 25 finding MEANS for the reader, or None where nothing was reallocated.

        Rendered here rather than left to the caller because the finding is useless as a bare enum
        value: "substantial_modification" beside a list of obligations does not tell anyone that
        the long column is now theirs. The note says which limb, what it costs, and — Art. 25(2) —
        that the party they bought from has stopped being the provider and owes them cooperation.
        That last half is the actionable one, and it is invisible from the value alone."""
        limb = self.becomes_provider
        if limb is None:
            return None
        if limb is ProviderReallocation.PRODUCT_MANUFACTURER:
            return (
                f"THE PROVIDER IS THE PRODUCT MANUFACTURER ({limb.citation}). This high-risk AI "
                f"system is a safety component of a product covered by Annex I Section A and goes "
                f"to market under the manufacturer's own name or trademark, so Art. 25(3) makes "
                f"that manufacturer the provider of the AI system and subjects it to Art. 16 "
                f"whole. The provider obligations in this report are the manufacturer's, not the "
                f"AI supplier's."
            )
        return (
            f"THE PROVIDER ROLE HAS MOVED ({limb.citation}). Art. 25(1) makes a distributor, "
            f"importer, deployer or other third party the provider of a high-risk AI system in "
            f"this circumstance, subject to the obligations of Art. 16 — the whole provider set, "
            f"not a share of it. The provider obligations in this report are owed by the party "
            f"that did this, not by the one that originally placed the system on the market. "
            f"Art. 25(2) is the other half: that original provider stops being the provider of "
            f"this system, and must cooperate with the new one — supplying the information, "
            f"technical access and assistance needed, in particular for the conformity "
            f"assessment. That duty falls away where the original provider clearly specified the "
            f"system was not to be turned into a high-risk one."
        )

    @model_validator(mode="after")
    def _findings_reference_real_targets(self, info: ValidationInfo) -> ComplianceReport:
        """Every finding must point at a real use case and a real rule.

        - use_case_id is checked against this report's own classification (always available).
        - rule_id is checked against the PolicyRuleset when one is supplied via the validation
          context: ComplianceReport.model_validate(data, context={"policy_spec": spec}).
          Without the spec we cannot verify rule ids, so we skip that check rather than guess."""
        known_use_cases = {uc.use_case_id for uc in self.classification.use_cases}
        for finding in self.findings:
            if finding.use_case_id not in known_use_cases:
                raise ValueError(
                    f"Finding for rule {finding.rule_id!r} references unknown use_case_id "
                    f"{finding.use_case_id!r}; known: {sorted(known_use_cases)}."
                )

        spec = (info.context or {}).get("policy_spec") if info.context else None
        if isinstance(spec, PolicyRuleset):
            known_rules = {rule.rule_id: rule for rule in spec.rules}
            for finding in self.findings:
                if finding.rule_id not in known_rules:
                    raise ValueError(
                        f"Finding references rule_id {finding.rule_id!r} not present in the "
                        f"loaded PolicyRuleset (spec_version={spec.spec_version})."
                    )
                # A dropped criterion would vanish from the report without a trace.
                declared = [c.norm_id for c in known_rules[finding.rule_id].criteria]
                reported = [c.norm_id for c in finding.criteria]
                if declared != reported:
                    raise ValueError(
                        f"Finding for rule {finding.rule_id!r} reports criteria {reported}, but "
                        f"the rule declares {declared}."
                    )
            for rule_id in [r for ids in self.not_document_verifiable.values() for r in ids]:
                if rule_id not in known_rules:
                    raise ValueError(
                        f"not_document_verifiable references rule_id {rule_id!r} not present "
                        f"in the loaded PolicyRuleset (spec_version={spec.spec_version})."
                    )
            report_norms = {norm.norm_id: norm for norm in spec.report_norms}
            for field_name, expected_kind in (
                ("permissions", "permission"),
                ("legal_consequences", "legal_consequence"),
                ("conditional_applicability", "applicability"),
            ):
                for norm_id in [
                    norm_id for ids in getattr(self, field_name).values() for norm_id in ids
                ]:
                    norm = report_norms.get(norm_id)
                    if norm is None:
                        raise ValueError(
                            f"{field_name} references norm_id {norm_id!r} not present in the "
                            f"loaded PolicyRuleset (spec_version={spec.spec_version})."
                        )
                    if norm.kind.value != expected_kind:
                        raise ValueError(
                            f"{field_name} references {norm_id!r} of kind {norm.kind.value}, "
                            f"not {expected_kind}."
                        )
        return self
