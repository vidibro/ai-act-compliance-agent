"""The output: per-rule findings and the assembled compliance report.

Cross-references are validated so a finding can never point at nothing:
  - use_case_id must match a use case in the report's ClassificationResult (always checked);
  - rule_id must exist in the loaded PolicySpec (checked when the spec is supplied via the
    validation context, e.g. ComplianceReport.model_validate(data, context={"policy_spec": spec})).
"""

from __future__ import annotations

from datetime import date, datetime

from pydantic import BaseModel, ValidationInfo, field_validator, model_validator

from aiact.schemas.classification import ClassificationResult
from aiact.schemas.enums import ActorRole, ProviderReallocation, Verdict
from aiact.schemas.policy import LegalSource, PolicySpec
from aiact.schemas.question import EVIDENCE_QUOTE_MAX, Answer, Confidence

# Modelled on the European Commission's own wording for their AI Act Compliance Checker, with a
# second paragraph this tool owes its own users: Art. 6(1) settles a system's risk class by
# reference to twenty OTHER instruments, so some answers are not answerable from the AI Act alone
# and a legal reviewer is not always the right reviewer.
DISCLAIMER = (
    "This report is generated by an automated tool and is provided for informational purposes "
    "only. It does not constitute legal advice, and it does not represent the assessment or "
    "official position of the European Commission or any other authority. The classification "
    "and findings may be incomplete or incorrect. You should consult a qualified legal "
    "professional before relying on any part of this report.\n\n"
    "Some questions the Regulation asks cannot be answered from the Regulation alone. Where an AI "
    "system is part of a regulated product — a medical device, machinery, a vehicle, and other "
    "categories listed in Annex I — its risk class depends on rules in that product's own "
    "legislation, which this tool does not apply. Those questions need a specialist in that "
    "sector, not only a lawyer. This tool does not attempt them: it reports what the "
    "documentation states, says when the answer is missing, and leaves the question open rather "
    "than guessing. An open question is unfinished work, not a clean result.\n\n"
    "Where a system is high-risk, this report asks whether you have BECOME its provider under "
    "Article 25 — a distributor, importer, deployer or other third party takes on the provider's "
    "obligations where it puts its name on a high-risk system, substantially modifies one, or "
    "changes the intended purpose of a system so that it becomes high-risk, and under Article "
    "25(3) a product manufacturer placing an AI system on the market with its product is the "
    "provider of it. That question is answered from what the documentation states about who "
    "placed the system on the market and what you do to it. Documentation written from a single "
    "party's point of view often shows neither, so silence here is not a finding that Article 25 "
    "leaves you alone. If any of those circumstances describes you, read this report's provider "
    "section as yours whatever it says."
)

class Finding(BaseModel):
    """The verdict on one PolicyRule for one use case.

    `citation` is a required LegalSource with no default: an uncited finding cannot be built.
    `rule_id` is kept as a plain id rather than the full rule — the rule already lives in the
    loaded PolicySpec, and embedding it here would duplicate every rule in every report."""

    rule_id: str  # references PolicyRule.rule_id in the loaded PolicySpec
    use_case_id: str  # which use case activated this rule
    role: ActorRole
    """WHOSE obligation this is. REQUIRED, with no default, for the same reason `citation` has
    none: a finding that cannot say whose duty it is would quietly become the provider's, and a
    deployer duty mis-attributed that way is worse than one left out — the provider cannot
    discharge it and will not know that.

    Art. 4 binds both roles, so the same rule can produce a finding for each — different duties
    held by different parties, and a report that could not tell them apart would report one of
    them twice and neither correctly."""

    verdict: Verdict
    evidence_quote: str | None = None
    evidence_chunk_id: str | None = None
    reasoning: str
    citation: LegalSource
    confidence: Confidence

    @field_validator("evidence_quote")
    @classmethod
    def _evidence_quote_is_a_quote(cls, v: str | None) -> str | None:
        if v is not None and len(v) > EVIDENCE_QUOTE_MAX:
            raise ValueError(
                f"evidence_quote must be under {EVIDENCE_QUOTE_MAX} chars "
                f"(got {len(v)}) — cite a pinpoint excerpt, do not dump a section."
            )
        return v

    @model_validator(mode="after")
    def _gap_and_inadequate_need_reasoning(self) -> Finding:
        """A GAP or INADEQUATE verdict is an accusation; it must justify itself."""
        if self.verdict in (Verdict.GAP, Verdict.INADEQUATE) and not self.reasoning.strip():
            raise ValueError(
                f"Finding for rule {self.rule_id!r}: verdict={self.verdict} requires "
                f"non-empty reasoning."
            )
        return self


class ReportSummary(BaseModel):
    """Verdict tallies, optionally broken down per use case."""

    total_applicable: int
    passed: int
    gaps: int
    inadequate: int
    needs_review: int
    per_use_case: dict[str, ReportSummary] | None = None  # counts broken down per use case
    per_role: dict[ActorRole, ReportSummary] | None = None
    """Counts broken down per duty-holder. A provider reading a combined total cannot tell which
    part of it is theirs to fix, and the deployer's half is not theirs to fix at all."""


class ComplianceReport(BaseModel):
    """The full assembled output for one SystemUnderReview against one PolicySpec."""

    system_id: str
    act_version_date: date
    spec_version: str
    generated_at: datetime
    classification: ClassificationResult
    findings: list[Finding]
    not_document_verifiable: dict[ActorRole, list[str]] = {}
    """Rule ids to confirm separately, keyed by WHO owes them — NOT gaps.

    Grouped by role because that is the only way the list is actionable: a provider cannot confirm
    that a deployer informed its workers under Art. 26(7).
    Roles owing nothing are absent rather than present-and-empty."""
    provider_reallocation: Answer | None = None
    """Art. 25 — whether the reader has BECOME the provider of a system someone else built.

    A statement about WHOSE the findings above are, which is why it sits on the report rather than
    on the classification: the tier is a fact about the system, this is a fact about the reader.
    `None` means the question was not put — Art. 25 reallocates the provider of a high-risk system
    and of nothing else — which is not the same as an answer of "nobody was reallocated"."""

    summary: ReportSummary
    scope_note: str | None = None
    """Why the obligation check covered what it did — set whenever `findings` is empty for a reason
    a reader would otherwise have to infer. An empty findings list reads as a clean bill of health,
    and for a prohibited practice or an out-of-scope system that reading is dangerously wrong."""
    disclaimer: str = DISCLAIMER

    @property
    def becomes_provider(self) -> ProviderReallocation | None:
        """The Art. 25 limb that made the reader the provider, or None.

        Narrowed by TYPE for the reason the cascade's own helpers are: only a recognised member is
        a finding that can be cited, and a reallocation nobody can cite is one the reader cannot
        check or contest."""
        answer = self.provider_reallocation
        value = answer.value if answer is not None else None
        return value if isinstance(value, ProviderReallocation) else None

    @property
    def provider_reallocation_note(self) -> str | None:
        """What an Art. 25 finding MEANS for the reader, or None where nothing was reallocated.

        Rendered here rather than left to the caller because the finding is useless as a bare enum
        value: "substantial_modification" beside a list of obligations does not tell anyone that
        the long column is now theirs. The note says which limb, what it costs, and — Art. 25(2) —
        that the party they bought from has stopped being the provider and owes them cooperation.
        That last half is the actionable one, and it is invisible from the value alone."""
        limb = self.becomes_provider
        if limb is None:
            return None
        if limb is ProviderReallocation.PRODUCT_MANUFACTURER:
            return (
                f"YOU ARE THE PROVIDER ({limb.citation}). This high-risk AI system is a safety "
                f"component of a product covered by Annex I Section A and is placed on the market "
                f"or put into service under your name or trademark, so Art. 25(3) makes the "
                f"product manufacturer the provider of it and subjects you to Art. 16 whole. Read "
                f"the provider obligations in this report as yours, not the AI supplier's."
            )
        return (
            f"YOU ARE THE PROVIDER ({limb.citation}). Art. 25(1) makes a distributor, importer, "
            f"deployer or other third party the provider of a high-risk AI system in this "
            f"circumstance, subject to the obligations of Art. 16 — the whole provider set, not a "
            f"share of it. Read the provider obligations in this report as yours. Art. 25(2) is "
            f"the other half: the party that originally placed this system on the market is no "
            f"longer its provider, and must cooperate with you and supply the information, "
            f"technical access and assistance you need — in particular for the conformity "
            f"assessment. Ask them for it. That duty does not apply where they clearly specified "
            f"the system was not to be turned into a high-risk one."
        )

    @model_validator(mode="after")
    def _findings_reference_real_targets(self, info: ValidationInfo) -> ComplianceReport:
        """Every finding must point at a real use case and a real rule.

        - use_case_id is checked against this report's own classification (always available).
        - rule_id is checked against the PolicySpec when one is supplied via the validation
          context: ComplianceReport.model_validate(data, context={"policy_spec": spec}).
          Without the spec we cannot verify rule ids, so we skip that check rather than guess."""
        known_use_cases = {uc.use_case_id for uc in self.classification.use_cases}
        for finding in self.findings:
            if finding.use_case_id not in known_use_cases:
                raise ValueError(
                    f"Finding for rule {finding.rule_id!r} references unknown use_case_id "
                    f"{finding.use_case_id!r}; known: {sorted(known_use_cases)}."
                )

        spec = (info.context or {}).get("policy_spec") if info.context else None
        if isinstance(spec, PolicySpec):
            known_rules = {rule.rule_id for rule in spec.rules}
            for finding in self.findings:
                if finding.rule_id not in known_rules:
                    raise ValueError(
                        f"Finding references rule_id {finding.rule_id!r} not present in the "
                        f"loaded PolicySpec (spec_version={spec.spec_version})."
                    )
            for rule_id in [r for ids in self.not_document_verifiable.values() for r in ids]:
                if rule_id not in known_rules:
                    raise ValueError(
                        f"not_document_verifiable references rule_id {rule_id!r} not present "
                        f"in the loaded PolicySpec (spec_version={spec.spec_version})."
                    )
        return self
